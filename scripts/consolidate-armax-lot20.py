root_md = root_md.replace('### Continuation courante — lot 19 et deux extensions', f'### Continuation courante — lot 20\n\nLe [lot20](docs/armax/lot20/README.md) poursuit les sprites fixes manquants. {summary} Les références, écarts et refus sont tracés ; aucun actif ne reçoit une certification 1:1 ou une nouvelle intégration moteur. Les guides et deux extensions intégrés au lot19 sont conservés.\n\n### Historique — lot 19 et deux extensions', 1)
