    if any('id="'+identifier+'"' in line for identifier in newly_illustrated):
        line = line.replace('| Sans image |', '| Image candidate lot20 |' if any(i in line for i in selected_ids) else '| Image candidate lot17 — attribution lot20 |')
    lines.append(line)
