    identifier = attribution['catalogId']
    entry = entries[identifier]
    path = attribution['path']
    assert identifier in targets and attribution['selected'] and not entry['assetFiles']
    assert path in {a['path'] for a in previous_attributions['unresolved']}
    assert sha(path) == attribution['sha256'] and path not in {a['path'] for a in assets}
    entry['assetFiles'].append(path)
    entry['pngCountLot17AtLot19'] = entry.get('pngCountLot17', 0)
    entry['pngCountLot17'] = sum('/lot17/' in p for p in entry['assetFiles'] + entry['alternateAssetFiles'])
    entry.update(status='Prototype', imageLot='lot17', attributionLot='lot20', latestAttributionRef=ATTR,
                 assetPresence='candidat_historique_attribue_fichier_present',
                 fidelity1to1Validated=False, engineIntegrated=False,
                 referenceReadiness='identite_visuelle_raccordee; details_1to1_et_moteur_non_valides')
    entry['assetAvailabilityEvidence'].append(dict(path=path, sha256=sha(path),
        origin='native_lot17_recovered_in_lot18_attributed_in_lot20', baseCommit=BASE,
        attributionRef=ATTR, nativeBytesPreserved=True))
    entry['productionNote'] += '\nLot20 : attribution d’un PNG historique lot17 déjà récupéré ; aucun nouveau fichier ni nouvelle génération pour ce rattachement.'
    entry['generationNotes'] = list(dict.fromkeys(entry.get('generationNotes', []) + attribution['reviewNotes'] + attribution['limits']))
    entry['referenceGap'] = ' '.join(attribution['limits'])
    entry['sourceUrls'] = list(dict.fromkeys(entry['sourceUrls'] + attribution['sourceUrls']))
