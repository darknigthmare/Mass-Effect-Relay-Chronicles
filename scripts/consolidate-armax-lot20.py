#!/usr/bin/env python3
"""Consolidate reviewed lot20 outputs while preserving all lot19 identities."""
from collections import Counter
from pathlib import Path
import copy
import hashlib
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
BASE = 'b83a62d277d93cd8140113ee2318745fcdedf8d6'
DATE = '2026-11-27'
LOT = 'docs/armax/lot20'
ART = LOT + '/art-production/manifest.json'
ATTR = LOT + '/recovered-attributions.json'
PARENT = 'docs/armax/lot19/production-catalog.json'
IDENTITY = ('id', 'category', 'name', 'work', 'dlc', 'variant', 'plannedUse', 'addedInLot')
GROUPS = ('human', 'costumes', 'aliens-officers')


def historic(path):
    return subprocess.check_output(['git', 'show', BASE + ':' + path], cwd=ROOT)


def data(path):
    return (ROOT / path).read_bytes() if (ROOT / path).is_file() else historic(path)


def read(path):
    return json.loads(data(path))


def sha(path):
    return hashlib.sha256(data(path)).hexdigest()


def write(path, value):
    target = ROOT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')


def markdown(path, value):
    (ROOT / path).write_text(value)


baseline = read(PARENT)
excluded = set(baseline['policy']['automaticRetryExcludedIds'])
targets = [e['id'] for e in baseline['entries'] if not e['assetFiles'] and e['id'] not in excluded]
assert len(targets) == 12
manifest = dict(schemaVersion=1, lot='lot20', createdOn=DATE, baseCommit=BASE,
                generationTool='builtin_image_gen', generationMode='fixed_sprites_only',
                fidelity1to1Validated=False, engineIntegrated=False,
                sourceManifests=[], assets=[], attempts=[], referenceSearches=[], qaFiles=[],
                targetCatalogIds=targets,
                referencePolicy='References inspected outside the repository; URLs, hashes and limits retained. Native generated bytes are unchanged.',
                qaScope='File and visual review only; no 1:1 or engine certification.')
for group in GROUPS:
    path = f'{LOT}/art-production/{group}/manifest.json'
    source = read(path)
    assert source['baseCommit'] == BASE and source['lot'] == 'lot20', path
    assert not any(a.get('outcome') in ('requested', 'running', 'pending') for a in source.get('attempts', [])), path
    manifest['sourceManifests'].append(dict(path=path, sha256=sha(path), group=group))
    for key in ('assets', 'attempts', 'referenceSearches', 'qaFiles'):
        manifest[key].extend(copy.deepcopy(source.get(key, [])))
assets = manifest['assets']
selected = [a for a in assets if a.get('selected', False)]
assert selected, 'Do not publish an empty production lot'
assert len({a['path'] for a in assets}) == len(assets)
assert len({a['assetId'] for a in assets}) == len(assets)
covered = {a.get('catalogId') for key in ('assets', 'attempts', 'referenceSearches') for a in manifest[key]}
assert set(targets).issubset(covered), set(targets) - covered
assert not (covered & excluded), 'Excluded targets must not be retried'
write(ART, manifest)

previous_attributions = read('docs/armax/lot19/recovered-attributions.json')
attribution_source = f'{LOT}/art-production/human/recovered-attributions.json'
new_attributions = read(attribution_source) if (ROOT / attribution_source).is_file() else {'associations': []}
recovered = new_attributions.get('associations', [])
resolved_paths = {a['path'] for a in recovered}
unresolved = [a for a in previous_attributions['unresolved'] if a['path'] not in resolved_paths]
attributions = dict(schemaVersion=1, lot='lot20', date=DATE, baseCommit=BASE,
                    priorReport='docs/armax/lot19/recovered-attributions.json',
                    scope='New identity decisions only; prior lot19 attributions remain historical.',
                    associations=recovered, unresolved=unresolved,
                    sourceReport=attribution_source if (ROOT / attribution_source).is_file() else None,
                    sourceReportSha256=sha(attribution_source) if (ROOT / attribution_source).is_file() else None,
                    references=copy.deepcopy(new_attributions.get('references', [])),
                    qaFiles=copy.deepcopy(new_attributions.get('qaFiles', [])),
                    referenceResolution='Reference IDs resolve in this report and in the hash-pinned sourceReport.',
                    newPngFiles=0, recoveredPngFilesThisTurn=0)
write(ATTR, attributions)

catalogue = copy.deepcopy(baseline)
entries = {e['id']: e for e in catalogue['entries']}
for entry in catalogue['entries']:
    entry['pngCountLot20'] = 0
for asset in assets:
    identifier = asset['catalogId']
    assert identifier in targets and identifier not in excluded, identifier
    entry = entries[identifier]
    path = asset['path']
    assert path.startswith('public/assets/armax/lot20/') and path.endswith('.png')
    assert sha(path) == asset['technical']['sha256']
    assert asset.get('fidelity1to1Validated') is False and asset.get('engineIntegrated') is False
    assert asset.get('plannedUse', entry['plannedUse']) == entry['plannedUse']
    entry['pngCountLot20'] += 1
    destination = entry['assetFiles'] if asset.get('selected') else entry['alternateAssetFiles']
    assert path not in destination
    destination.append(path)
    entry['assetAvailabilityEvidence'].append(dict(path=path, sha256=sha(path), origin='builtin_imagegen_lot20',
                                                  baseCommit=BASE, manifestRef=ART, nativeBytesPreserved=True))
    entry['sourceUrls'] = list(dict.fromkeys(entry['sourceUrls'] + asset.get('sourceUrls', [])))
    notes = asset.get('reviewNotes', [])
    if isinstance(notes, str):
        notes = [notes]
    entry['generationNotes'] = list(dict.fromkeys(entry.get('generationNotes', []) + notes))
    entry['latestManifestRef'] = ART
    entry['latestGenerationAttempt'] = 'generated'
    if asset.get('selected'):
        entry.update(status='Prototype', imageLot='lot20', assetPresence='candidat_genere_fichier_present',
                     fidelity1to1Validated=False, engineIntegrated=False,
                     referenceReadiness='candidat_documente; comparaison_1to1_et_moteur_non_validees')
        entry['productionNote'] += '\nLot20 : image fixe candidate référencée ; identité, opus, variante et rôle conservés. Fidélité et intégration moteur à valider.'
        entry['referenceGap'] = ' '.join(notes) or 'Comparer la silhouette complète aux références exactes puis contrôler en moteur.'
