import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MEDIA_PERIODS, COMMON28, getEntryContinuity } from '../src/continuity-data.js';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const groupCategories = {
  actors: ['characters', 'npcs', 'enemies'],
  equipment: ['weapons', 'equipment'],
  powers: ['powers'],
  story: ['lore', 'main_quests', 'side_quests', 'choices', 'dialogues', 'cinematics', 'worlds', 'zones', 'continuity', 'links'],
};
const strings = value => Array.isArray(value) ? [...new Set(value.filter(item => typeof item === 'string' && item))] : [];
const text = value => typeof value === 'string' ? value : '';

/** Reads documentary inputs only; never rewrites a catalogue or spreadsheet. */
export async function buildUniverseRuntime(root = projectRoot) {
  const manifest = JSON.parse(await readFile(path.join(root, 'docs/universe/manifest.json'), 'utf8'));
  if (manifest.workbooks.length !== 27) throw new Error('Expected the 27-work manifest plus the principal ME1 catalogue.');
  const inputs = [{ id: 'ME1', catalogPath: 'docs/content-catalog.json' }, ...manifest.workbooks];
  if (inputs.map(input => input.id).join('|') !== COMMON28.join('|')) throw new Error('Manifest order/IDs differ from MEDIA_PERIODS.');
  const works = [], rows = [], seen = new Set(), digests = [];
  for (const input of inputs) {
    const raw = await readFile(path.join(root, input.catalogPath), 'utf8');
    const data = JSON.parse(raw), media = MEDIA_PERIODS.find(item => item.id === input.id);
    digests.push([input.catalogPath, createHash('sha256').update(raw).digest('hex')]);
    if (!Array.isArray(data.entries) || !Array.isArray(data.sources)) throw new Error(`Invalid catalogue ${input.id}.`);
    const sourceIds = new Set(data.sources.map(source => source.id));
    for (const segment of media.periods) {
      for (const source of segment.sourceIds) if (!sourceIds.has(source)) throw new Error(`Unknown period source ${input.id}/${segment.id}/${source}.`);
    }
    works.push({
      ...media, title: ['ME1', 'ME4'].includes(input.id) ? media.title : data.title,
      catalogId: input.id, catalogPath: input.catalogPath, count: data.entries.length,
      scope: text(data.scope || data.meta?.scope),
      canonNote: input.id === 'ME4' ? `${media.reason} ${media.verificationNote}` : text(data.canonNote || data.meta?.fidelity),
      sources: data.sources,
    });
    for (const entry of data.entries) {
      if (!entry.id || seen.has(entry.id)) throw new Error(`Duplicate/empty catalogue ID: ${entry.id}`);
      seen.add(entry.id);
      const continuity = getEntryContinuity(input.id, entry);
      const references = strings([entry.sourceId, ...strings(entry.sourceIds)]);
      for (const source of references) if (!sourceIds.has(source)) throw new Error(`Unknown entry source ${entry.id}/${source}.`);
      rows.push([
        entry.id, input.id, continuity.mediaId, text(entry.category), text(entry.name), text(entry.status),
        continuity.nature, text(entry.canonLevel), text(entry.description), text(entry.conditions),
        references, text(entry.sourceUrl), text(entry.reference), text(entry.notes),
        continuity.availability.flatMap(item => item.periodIds), continuity.lockReason,
        continuity.continuityReferences, strings(entry.dependencies),
      ]);
    }
  }
  const sourceCount = works.reduce((sum, item) => sum + item.sources.length, 0);
  const summary = {
    schemaVersion: 1, catalogCount: works.length, recordCount: rows.length, sourceCount,
    factualCount: rows.filter(row => row[6] === 'Établi').length,
    contextualCount: rows.filter(row => row[14].length).length,
    playableCount: 0,
    catalogDigests: Object.fromEntries(digests),
  };
  // Tuples avoid repeating 18 field names thousands of times in the browser
  // bundle. The public API below exposes ordinary immutable record objects.
  const source = `// Generated by scripts/build-universe-runtime.mjs. Do not edit.
// Documentary records only: original statuses retained; playable is always false.
import { evaluateContinuity } from './continuity-data.js';

const freeze = value => {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    for (const child of Object.values(value)) freeze(child);
    Object.freeze(value);
  }
  return value;
};
export const UNIVERSE_SUMMARY = freeze(${JSON.stringify(summary)});
export const UNIVERSE_WORKS = freeze(${JSON.stringify(works)});
const WORKS = new Map(UNIVERSE_WORKS.map(work => [work.id, work]));
const ROWS = ${JSON.stringify(rows)};
export const UNIVERSE_RECORDS = freeze(ROWS.map(row => {
  const [id,catalogWorkId,mediaId,category,name,status,nature,canonLevel,description,conditions,sourceIds,sourceUrl,reference,notes,periodIds,lockReason,continuityReferences,dependencies] = row;
  return {id,catalogId:id,catalogWorkId,mediaId,category,name,status,nature,canonLevel,description,conditions,sourceIds,sourceUrl,reference,notes,dependencies,
    fact:nature === 'Établi',playable:false,lockReason,
    availability:periodIds.length ? [{mediaId,periodIds}] : [],
    provenance:{catalogPath:WORKS.get(catalogWorkId).catalogPath,sourceIds,sourceUrl,reference,continuityReferences}};
}));
const RECORDS = new Map(UNIVERSE_RECORDS.map(record => [record.id, record]));
const GROUP_CATEGORIES = ${JSON.stringify(groupCategories)};
export const UNIVERSE_GROUPS = freeze(Object.fromEntries(Object.entries(GROUP_CATEGORIES).map(([group,categories]) =>
  [group, UNIVERSE_RECORDS.filter(record => record.fact && categories.includes(record.category))])));
export function getUniverseRecord(id) { return typeof id === 'string' ? RECORDS.get(id) || null : null; }
export function getUniverseWork(id) { return typeof id === 'string' ? WORKS.get(id) || null : null; }
export function getUniverseRecords(context, {group} = {}) {
  const records = group === undefined ? UNIVERSE_RECORDS : Object.hasOwn(UNIVERSE_GROUPS, group) ? UNIVERSE_GROUPS[group] : [];
  return records.filter(record => evaluateContinuity(record, context));
}
`;
  return { source, summary };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.some(arg => !['--check', '--help'].includes(arg))) throw new Error('Usage: node scripts/build-universe-runtime.mjs [--check]');
  if (args.includes('--help')) {
    console.log('node scripts/build-universe-runtime.mjs [--check]\nBuild the documentary runtime registry from the principal catalogue and 27-work manifest. --check does not write.');
    return;
  }
  const { source, summary } = await buildUniverseRuntime();
  const output = path.join(projectRoot, 'src/universe-data.js');
  if (args.includes('--check')) {
    if (await readFile(output, 'utf8') !== source) throw new Error('src/universe-data.js is stale; rebuild the runtime registry.');
  } else await writeFile(output, source);
  console.log(JSON.stringify({ ok: true, mode: args.includes('--check') ? 'check' : 'build', ...summary }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
